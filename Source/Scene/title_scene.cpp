// =================================================================
// 更新処理
// =================================================================
void TitleScene::Update()
{
    // Enterキーが押されたら決定音を再生してチュートリアルへ
    if (Input::GetKeyTrigger(VK_RETURN)) {
        SoundManager::PlaySE(SoundID::SE_DECIDE);
        Manager::ChangeScene(Scene::TUTORIAL);
    }
}

