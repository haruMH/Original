#pragma once

// =================================================================
// シーン共通インターフェースクラス (IScene)
// =================================================================
// ゲーム内の各画面（シーン）が実装すべき共通ルールを定めます。
// ポリモーフィズム（多態性）を用いて、Managerがどのシーンに対しても
// 同じ方法で初期化・更新・描画・終了処理を行えるようにします。
class IScene
{
public:
    virtual ~IScene() {}

    // シーン切り替え時に呼ばれる初期化処理
    virtual void Init() = 0;

    // シーン遷移時やゲーム終了時に呼ばれる終了（解放）処理
    virtual void Uninit() = 0;

    // 毎フレームの更新処理（入力受付やゲームロジックの実行）
    virtual void Update() = 0;

    // 毎フレームの描画処理（オブジェクトやUIの描画要求）
    virtual void Draw() = 0;
};
