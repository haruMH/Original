#include "wall.h"
#include "renderer.h"
#include "resource_manager.h"

// =================================================================
// 初期化
// =================================================================
void Wall::Init()
{
    m_Position = XMFLOAT3(0.0f, 0.0f, 0.0f);
    m_Rotation = XMFLOAT3(0.0f, 0.0f, 0.0f);
    m_Scale    = XMFLOAT3(1.0f, 1.0f, 1.0f);
    m_Size     = XMFLOAT3(1.0f, 1.0f, 1.0f);

    m_Texture = ResourceManager::GetTexture("grid.png");

    // コンポーネント指向での描画パラメータ初期化（インスタンスバッチ描画の対象にする）
    m_RenderComponent = RenderComponent("grid.png", MeshType::Cube, true);
}

// =================================================================
// 終了処理
// =================================================================
void Wall::Uninit()
{
}

// =================================================================
// 更新処理
// =================================================================
void Wall::Update()
{
    // 本編の壁は静的オブジェクトのため、毎フレームの更新は行いません
}

// =================================================================
// 個別描画処理
// =================================================================
void Wall::Draw()
{
    // 通常・シャドウ・アウトラインの描画は RenderSystem 側で一括描画するため、
    // ここでの個別描画（DrawIndexed）は行いません。
}
